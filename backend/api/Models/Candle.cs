using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Microsoft.EntityFrameworkCore;
using NetTopologySuite.Geometries;

namespace CandleBackend.Models;

[Index(nameof(CreatedAt), nameof(Id))]
[Index(nameof(UserId), nameof(CreatedAt), nameof(Id))]
public class Candle
{
    public long Id { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime IgnitedAt { get; set; }
    public DateTime ExtinguishedAt { get; set; }
    public string? Message { get; set; }

    /// <summary>
    /// Where the candle was lit, as a WGS84 (SRID 4326) point: X is longitude,
    /// Y is latitude. Null for candles created before locations existed.
    /// </summary>
    [Column(TypeName = "geometry(Point,4326)")]
    public Point? Location { get; set; }

    /// <summary>
    /// <see cref="Location"/> projected to Web Mercator (SRID 3857), in metres,
    /// as columns generated by the database. The map draws in Web Mercator, so
    /// a grid with a constant step over these is a grid with a constant step on
    /// screen - no latitude correction, and the antimeridian is just the edge of
    /// the world square rather than a discontinuity. Projecting on write also
    /// keeps the grouping query to plain arithmetic.
    /// </summary>
    public double? MercatorX { get; private set; }

    /// <inheritdoc cref="MercatorX"/>
    public double? MercatorY { get; private set; }

    public const int AddressMaxLength = 300;

    /// <summary>
    /// The address of <see cref="Location"/> as the author picked it. Null when
    /// none was given, and reset whenever the location moves without a new one.
    /// </summary>
    [MaxLength(AddressMaxLength)]
    public string? Address { get; set; }

    public Guid? BackgroundResourceId { get; set; }
    [DeleteBehavior(DeleteBehavior.Restrict)]
    public MediaResource? BackgroundResource { get; set; }

    public long UserId { get; set; }
    public User User { get; set; } = null!;
}
